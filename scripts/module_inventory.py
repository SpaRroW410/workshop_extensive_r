#!/usr/bin/env python3
"""Module inventory: one row per teaching page, so nothing is missed when modules are updated.

Usage (repository root):  python3 scripts/module_inventory.py > MODULE_INVENTORY.md

Reads curriculum.yml (menu pages) and follows links from hub pages to their sub-decks (plot galleries).
Workshops (*-workshop/) and the game (dungeons/) are summarised per folder, not per page.
Flags:
  stub        no code at all, no links to sub-decks, under 80 lines (an outline, not teaching material)
  practice    fill-in exercises with _____ blanks (not run on purpose)
  no-output   most R chunks have eval=FALSE, so the reader sees code but no result
  ext-data    reads a dataset that has no make_data script and no entry in data/README.md
Add --check to exit 1 when a menu page is flagged stub or no-output (used by CI).
"""
import glob, os, re, sys
import yaml

c = yaml.safe_load(open('curriculum.yml'))
pages, profs = c['pages'], c['profiles']
SITE = {'contact.qmd', 'references.qmd', 'downloads.qmd', 'advanced-workshops.qmd'}
EXT_DATA = ('PublicHealth_BP_Dataset.xlsx', 'health_dataset_dm.xlsx', 'Healthcare_Network_Dataset.xlsx', 'prac_modded.xlsx')
# A dataset whose origin is written down in data/README.md is documented (D5), so it is not flagged.
_readme = open('data/README.md').read() if os.path.exists('data/README.md') else ''
EXT_DATA = tuple(d for d in EXT_DATA if f'`{d}`' not in _readme)


def walk(x, out):
    if isinstance(x, str):
        if x.endswith('.qmd'):
            out.add(x)
    elif isinstance(x, dict):
        for k, v in x.items():
            if k == 'path' and isinstance(v, str):
                out.add(v)
            else:
                walk(v, out)
    elif isinstance(x, list):
        for i in x:
            walk(i, out)


tracks = {}
for p, cfg in profs.items():
    s = set()
    walk(cfg, s)
    for q in s:
        tracks.setdefault(q, []).append(p)

is_workshop = lambda p: re.match(r'([\w-]+-workshop|dungeons)/', p)
base = [p for p in pages if not is_workshop(p) and p not in SITE]

# sub-decks linked from hub pages (e.g. plot galleries)
rows = []
for p in base:
    rows.append((p, None))
    for m in re.findall(r'\]\(([^)#\s]+\.qmd)', open(p).read()):
        sub = os.path.normpath(os.path.join(os.path.dirname(p), m))
        if os.path.exists(sub) and sub not in pages and not any(r[0] == sub for r in rows):
            rows.append((sub, p))


def info(p):
    t = open(p).read()
    fm = t.split('---', 2)[1] if t.startswith('---') else ''
    body = t.split('---', 2)[2] if t.startswith('---') else t
    chunks = len(re.findall(r'^```\{r', t, re.M))
    noeval = len(re.findall(r'eval *= *FALSE|#\| *eval: *false', t))
    lines = [l for l in body.splitlines() if l.strip()]
    bullets = sum(1 for l in lines if re.match(r'\s*[-*] ', l))
    flags = []
    hub = re.search(r'\]\([^)]+\.qmd\)', body)
    if chunks == 0 and '```' not in body and not hub and len(lines) < 80:
        flags.append('stub')
    if '_____' in t:
        flags.append('practice')          # fill-in exercises: code not run on purpose
    elif chunks >= 3 and noeval >= chunks - 1:
        flags.append('no-output')
    if any(d in t for d in EXT_DATA):
        flags.append('ext-data')
    date = re.search(r'^date:\s*"?([^"\n]*)', fm, re.M)
    author = re.search(r'^author:\s*(.*)$', fm, re.M)
    return dict(fmt='deck' if 'revealjs' in fm else 'page', lines=len(t.splitlines()), chunks=chunks,
                quiz=len(re.findall(r'quiz_mcq|quiz_fill|quiz-q', t)),
                date=date.group(1) if date else '—', author='yes' if author else '—', flags=' '.join(flags) or '')


out = sys.stdout
out.write('# Module inventory\n\nGenerated by `scripts/module_inventory.py`; do not edit by hand. '
          'Flags: **stub** = outline only; **no-output** = code shown but not run, so no plots or tables appear; **practice** = fill-in exercises (not run on purpose); **ext-data** = dataset without a make_data script or an entry in `data/README.md`.\n\n')
out.write('## Base modules (menu pages and the sub-decks they link to)\n\n')
out.write('| Page | Linked from | Tracks | Format | Lines | R chunks | Quiz Qs | Date | Author | Flags |\n|---|---|---|---|---|---|---|---|---|---|\n')
bad = []
for p, parent in rows:
    i = info(p)
    if any(fl in i['flags'].split() for fl in ('stub', 'no-output')):
        bad.append(f"{p}: {i['flags']}")
    tr = ', '.join(sorted(tracks.get(p, tracks.get(parent, []))))
    out.write(f"| `{p}` | {('`' + parent + '`') if parent else ''} | {tr} | {i['fmt']} | {i['lines']} | {i['chunks']} | {i['quiz']} | {i['date']} | {i['author']} | {i['flags']} |\n")

out.write('\n## Workshops\n\n| Folder | Decks | Quiz Qs | Labs | Solutions | Cheat sheet | README | make_data | Reviewed |\n|---|---|---|---|---|---|---|---|---|\n')
for w in sorted(glob.glob('*-workshop')):
    decks = sorted(glob.glob(f'{w}/s[0-9]*.qmd'))
    q = sum(len(re.findall(r'quiz_mcq|quiz_fill', open(d).read())) for d in decks)
    md = os.path.exists(f'{w}/make_data.R') or w in ('regression-workshop', 'gis-workshop')
    rev = 'yes' if re.search(r'Reviewed by', open(f'{w}/README.md').read()) else 'no'
    out.write(f"| `{w}` | {len(decks)} | {q} | {len(glob.glob(f'{w}/labs/*.R'))} | {len(glob.glob(f'{w}/solutions/*.R'))} | "
              f"{'yes' if os.path.exists(f'{w}/cheatsheet.qmd') else 'no'} | {'yes' if os.path.exists(f'{w}/README.md') else 'no'} | {'yes' if md else 'no'} | {rev} |\n")

out.write('\n## Game (dungeons/)\n\n')
w = open('dungeons/assets/worlds.js').read()
for reg in ('r1', 'r2', 'r3', 'r4'):
    ws = re.findall(r"\{ id: '(\w+)', region: '%s'.*?status: '(\w+)'" % reg, w)
    out.write(f"- Region {reg[1]}: {len(ws)} worlds, " + (', '.join(f'{a} ({b})' for a, b in ws) or 'none') + '\n')

out.write('\n## Datasets without a make_data script\n\n')
if not EXT_DATA:
    out.write('None: every dataset has a make_data script or an entry in `data/README.md`.\n')
for d in EXT_DATA:
    users = [p for p in glob.glob('**/*.qmd', recursive=True) if not p.startswith(('docs/', 'archive/', '_freeze/')) and d in open(p).read()]
    out.write(f"- `data/{d}`: used by {len(users)} pages\n")

if '--check' in sys.argv and bad:
    sys.stderr.write('Menu pages that are outlines or show code without output (D1):\n  ' + '\n  '.join(bad) + '\n')
    sys.exit(1)
