# F8: list every R package the site uses, with the version it was last rendered with, per track.
# Writes PACKAGES.md. Run from the repo root after a successful render: Rscript scripts/package_versions.R
# A fresh machine can install these versions with remotes::install_version(pkg, version).
pages <- jsonlite::fromJSON("_filters/pages.json")$profiles
pkgs_in <- function(f) {
  if (!file.exists(f)) return(character(0))
  x <- readLines(f, warn = FALSE)
  a <- regmatches(x, gregexpr("(?<![\\w.])(library|require|requireNamespace)\\(\\s*[\"']?([A-Za-z][A-Za-z0-9.]+)", x, perl = TRUE))
  b <- regmatches(x, gregexpr("\\b([A-Za-z][A-Za-z0-9.]+)::", x, perl = TRUE))
  p <- c(sub(".*\\(\\s*[\"']?", "", unlist(a)), sub("::$", "", unlist(b)))
  unique(p)
}
labs <- Sys.glob(c("labs/*/solutions/*.R", "*-workshop/labs/solutions/*.R", "*-workshop/make_data.R", "gis/*.R", "assets/*.R"))
rows <- list()
for (tr in names(pages)) {
  files <- c(pages[[tr]], if (tr == "basic") Sys.glob("labs/basic/solutions/*.R"),
             if (tr == "moderate") Sys.glob("labs/moderate/solutions/*.R"),
             if (tr == "dataviz-complete") Sys.glob("labs/dataviz/solutions/*.R"))
  ws <- unique(sub("/.*", "", grep("-workshop/", files, value = TRUE)))
  files <- c(files, unlist(lapply(ws, function(w) Sys.glob(file.path(w, c("labs/solutions/*.R", "make_data.R"))))))
  for (p in unique(unlist(lapply(files, pkgs_in)))) rows[[length(rows) + 1]] <- data.frame(track = tr, pkg = p)
}
d <- unique(do.call(rbind, rows))
base <- rownames(installed.packages(priority = "base"))
d <- d[!d$pkg %in% c(base, "R", "pkg", "x", "p", "any", "package"), ]
ver <- vapply(unique(d$pkg), function(p) tryCatch(as.character(packageVersion(p)), error = function(e) "— (only named in code that is shown, not run)"), "")
tab <- aggregate(track ~ pkg, d, function(t) paste(sort(unique(t)), collapse = ", "))
tab$version <- ver[tab$pkg]
tab <- tab[order(tolower(tab$pkg)), c("pkg", "version", "track")]
out <- c("# R packages used by the site",
         "",
         sprintf("Generated by `scripts/package_versions.R` on %s with %s. Versions are the ones the site was last rendered with.", Sys.Date(), R.version.string),
         "Install one version on a fresh machine with `remotes::install_version(\"pkg\", \"x.y.z\")`. Quarto: 1.11.9.",
         "",
         "| Package | Version | Tracks |", "|---|---|---|",
         sprintf("| %s | %s | %s |", tab$pkg, tab$version, tab$track))
writeLines(out, "PACKAGES.md")
cat(nrow(tab), "packages;", sum(grepl("^—", tab$version)), "shown-only\n")
invisible(NULL)
