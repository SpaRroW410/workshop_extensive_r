#!/usr/bin/env bash
# The quiz engine and its styles are identical in every workshop. regression-workshop/assets/ holds the master copy.
#   scripts/sync_workshop_assets.sh          copy the master files into every other *-workshop/assets/
#   scripts/sync_workshop_assets.sh --check  exit 1 if any copy differs (used by CI)
set -euo pipefail
cd "$(dirname "$0")/.."
files="quiz.js quiz.R quiz.css quiz-include.html"
status=0
for d in *-workshop; do
  [ "$d" = "regression-workshop" ] && continue
  for f in $files; do
    if [ "${1:-}" = "--check" ]; then
      cmp -s "regression-workshop/assets/$f" "$d/assets/$f" || { echo "DIFFERS: $d/assets/$f"; status=1; }
    else
      cp "regression-workshop/assets/$f" "$d/assets/$f"
    fi
  done
done
# Base modules (pages outside the workshops) use one self-contained include at the site root, so a page in any
# folder can load the engine with  include-after-body: ../assets/quiz-inline.html  (no relative script paths):
#   assets/quiz.R            copy of the master quiz.R  (source("../assets/quiz.R") in a page's setup chunk)
#   assets/quiz-inline.html  master quiz.css and quiz.js inlined
inline=$(mktemp)
{ echo "<!-- GENERATED by scripts/sync_workshop_assets.sh from regression-workshop/assets/quiz.css and quiz.js. Do not edit. -->"
  echo "<style>"; cat regression-workshop/assets/quiz.css; echo "</style>"
  echo "<script>"; cat regression-workshop/assets/quiz.js; echo "</script>"; } > "$inline"
if [ "${1:-}" = "--check" ]; then
  cmp -s regression-workshop/assets/quiz.R assets/quiz.R || { echo "DIFFERS: assets/quiz.R"; status=1; }
  cmp -s "$inline" assets/quiz-inline.html || { echo "DIFFERS: assets/quiz-inline.html"; status=1; }
else
  cp regression-workshop/assets/quiz.R assets/quiz.R
  cp "$inline" assets/quiz-inline.html && chmod 644 assets/quiz-inline.html
fi
rm -f "$inline"
[ "${1:-}" = "--check" ] && [ $status -eq 0 ] && echo "All workshop quiz assets match the master copy"
exit $status
